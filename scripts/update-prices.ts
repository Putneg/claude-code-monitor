import { writeFileSync } from 'node:fs';
import { DEFAULT_PRICING_URL, isAllowedPricingUrl, PRICING_URL_RULE } from '../src/server/config.js';
import { normalizeLiteLlm } from '../src/server/pricing/litellm.js';
import { createFetchPayload } from '../src/server/pricing/refresher.js';

const OUTPUT = new URL('../src/server/pricing/snapshot.ts', import.meta.url);

async function main(): Promise<void> {
  const url = process.env.PRICING_URL ?? DEFAULT_PRICING_URL;
  if (!isAllowedPricingUrl(url)) {
    console.error(`Invalid configuration: PRICING_URL: ${PRICING_URL_RULE}`);
    process.exit(1);
  }
  const { prices } = normalizeLiteLlm(await createFetchPayload(url, 30_000)());
  const count = Object.keys(prices).length;
  if (count === 0) throw new Error('No Anthropic or OpenAI prices found in the LiteLLM payload');
  const snapshot = { fetchedAt: new Date().toISOString(), prices };
  const body = [
    '// Generated by scripts/update-prices.ts from the LiteLLM price list. Do not edit by hand.',
    "import type { PriceSnapshot } from './types.js';",
    '',
    `export const PRICE_SNAPSHOT: PriceSnapshot = ${JSON.stringify(snapshot, null, 2)};`,
    '',
  ].join('\n');
  writeFileSync(OUTPUT, body);
  console.log(`Wrote ${count} Anthropic and OpenAI price entries to src/server/pricing/snapshot.ts`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
